def plot(runs: list[dict], path: Path) -> None:
    import matplotlib
    matplotlib.use('Agg')
    import matplotlib.pyplot as plt

    datasets = sorted({r['dataset'] for r in runs},
                      key=lambda name: next(x['pixels'] for x in runs
                                            if x['dataset'] == name))
    colours = {'cpp': '#1f4e79', 'py': '#c0504d'}
    # Distinct markers because the two miss-rate curves sit on top of each
    # other at 0% and at 100%, and a hidden curve is a misread plot.
    markers = {'cpp': 'o', 'py': 's'}
    dashes = ['-', '--', ':', '-.']

    figure, axes = plt.subplots(2, 1, figsize=(8.0, 8.0), sharex=True)
    upper, lower = axes

    for d_index, dataset in enumerate(datasets):
        style = dashes[d_index % len(dashes)]
        for impl in ('cpp', 'py'):
            rows = sorted((r for r in runs if r['impl'] == impl
                           and r['dataset'] == dataset),
                          key=lambda r: r['rate_hz'])
            if not rows:
                continue
            rates = [r['rate_hz'] for r in rows]
            p50 = [r['compute']['p50'] / 1e6 for r in rows]
            p99 = [r['compute']['p99'] / 1e6 for r in rows]
            label = f'{impl} {dataset.replace("table_", "")}'
            upper.plot(rates, p50, style, color=colours[impl],
                       marker=markers[impl], markersize=5, label=label)
            upper.fill_between(rates, p50, p99, color=colours[impl],
                               alpha=0.12, linewidth=0)
            lower.plot(rates, [100.0 * r['deadline_miss_rate'] for r in rows],
                       style, color=colours[impl], marker=markers[impl],
                       markersize=5, markerfacecolor='none', label=label)

    rates = sorted({r['rate_hz'] for r in runs})
    upper.plot(rates, [1000.0 / r for r in rates], color='0.35',
               linewidth=1.0, linestyle=(0, (6, 3)),
               label='control period (the budget)')
    upper.set_xscale('log')
    upper.set_yscale('log')
    upper.set_ylabel('pipeline latency, ms\n(p50 line, p50 to p99 shaded)')
    upper.set_title('Latency against control rate, and what it costs in misses')
    upper.grid(True, which='both', alpha=0.25)
    upper.legend(fontsize=8, loc='upper right', ncol=2)

    lower.set_xscale('log')
    lower.set_xlabel('control rate, Hz')
    lower.set_ylabel('deadline misses, %')
    lower.set_ylim(-4, 104)
    lower.set_xticks(rates)
    lower.set_xticklabels([f'{r:g}' for r in rates])
    lower.grid(True, which='both', alpha=0.25)

    figure.tight_layout()
    path.parent.mkdir(parents=True, exist_ok=True)
    figure.savefig(path, dpi=150)
    plt.close(figure)


def main(argv=None) -> int:
    config_text = DEFAULT_CONFIG.read_text()
    config = json.loads(config_text)
    sweep = config['rate_sweep']
    analysis = config['analysis']

    parser = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--dataset', type=Path, action='append', default=None,
                        help='frame store directory; repeatable. Defaults to '
                             'rate_sweep.datasets in the config')
    parser.add_argument('--data-root', type=Path, default=REPO_ROOT / 'data')
    parser.add_argument('--impl', action='append', default=None,
                        choices=('cpp', 'py'),
                        help='repeatable; defaults to both')
    parser.add_argument('--rates', type=float, nargs='+',
                        default=sweep['rates_hz'])
    parser.add_argument('--jobs', type=int, default=sweep['jobs_per_rate'])
    parser.add_argument('--warmup', type=int, default=sweep['warmup_jobs'])
    parser.add_argument('--out-dir', type=Path, default=REPO_ROOT / 'results')
    parser.add_argument('--build-dir', type=Path,
                        default=REPO_ROOT / 'cpp' / 'build')
    parser.add_argument('--config', type=Path, default=DEFAULT_CONFIG)
    parser.add_argument('--chain', type=Path,
                        default=REPO_ROOT / 'assets' / 'franka' / 'panda_chain.json')
    parser.add_argument('--ransac-table', type=Path,
                        default=REPO_ROOT / 'assets' / 'ransac_uniform.bin')
    parser.add_argument('--no-plot', action='store_true')
    args = parser.parse_args(argv)

    directories = args.dataset or [args.data_root / name
                                   for name in sweep['datasets']]
    implementations = args.impl or ['cpp', 'py']
    wanted = analysis['percentiles']
    method = analysis['percentile_method']

    runs: list[dict] = []
    worker_metadata: dict[str, dict] = {}

    for directory in directories:
        store = FrameStore(Path(directory))
        for impl in implementations:
            if impl == 'cpp':
                worker = CppWorker(store, args.config, args.chain,
                                   args.ransac_table, args.build_dir)
            else:
                worker = PythonWorker(store, args.config, args.chain,
                                      args.ransac_table)
            worker_metadata[impl] = worker.metadata()
            try:
                for rate in args.rates:
                    period_ns = int(round(NS_PER_S / rate))
                    release, start, finish, _frames, results = run_schedule(
                        worker, store, args.jobs, period_ns, args.warmup)
                    run = summarise(impl, store, rate, period_ns, release,
                                    start, finish, results, wanted, method)
                    runs.append(run)
                    print(f"{impl:>4} {store.name:<16} {rate:>6.1f} Hz  "
                          f"p50 {run['compute']['p50'] / 1e6:7.2f} ms  "
                          f"p99 {run['compute']['p99'] / 1e6:7.2f} ms  "
                          f"misses {100 * run['deadline_miss_rate']:5.1f}%  "
                          f"worst finish "
                          f"{run['worst_finish_vs_deadline_periods']:+6.2f} "
                          f"periods vs deadline", flush=True)
            finally:
                worker.close()

    report = {
        'metadata': {
            'generated_at_utc': time.strftime('%Y-%m-%dT%H:%M:%SZ',
                                              time.gmtime()),
            'scheduler': 'absolute deadlines from one monotonic origin, '
                         'time.perf_counter_ns',
            'jobs_per_rate': args.jobs,
            'warmup_jobs': args.warmup,
            'rates_hz': list(args.rates),
            'percentile_method': method,
            'workers': worker_metadata,
            'host': {
                'platform': platform.platform(),
                'cpu_count': os.cpu_count(),
                'load_average': list(os.getloadavg()),
            },
        },
        'runs': runs,
        'onset': onset(runs),
    }

    args.out_dir.mkdir(parents=True, exist_ok=True)
    (args.out_dir / 'rate_sweep.json').write_text(
        json.dumps(report, indent=2) + '\n', encoding='utf-8')
    with (args.out_dir / 'rate_sweep.csv').open('w', newline='',
                                                encoding='utf-8') as handle:
        writer = csv.DictWriter(handle, fieldnames=CSV_COLUMNS)
        writer.writeheader()
        writer.writerows(csv_rows(runs))
    if not args.no_plot:
        plot(runs, args.out_dir / 'rate_sweep.png')

    print(f'wrote {args.out_dir}/rate_sweep.json, rate_sweep.csv'
          + ('' if args.no_plot else ', rate_sweep.png'))
    for row in report['onset']:
        clean = row['highest_clean_rate_hz']
        print(f"  {row['impl']:>4} {row['dataset']:<16} "
              f"highest clean rate "
              f"{'none swept' if clean is None else f'{clean:g} Hz'}, "
              f"sustainable from p99 {row['sustainable_hz_p99']:.1f} Hz")
    return 0


