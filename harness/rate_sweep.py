#!/usr/bin/env python3
"""Drive both pipelines at fixed control rates and count what they miss.

The in-process benchmark answers "how long does one frame take". A control
loop asks a different question: given a period, how often is the answer late,
and by how much. Those are not the same question, because a pipeline whose p50
fits inside the period can still fall behind whenever the tail lands, and
because falling behind once delays the release of the next job.

The scheduler here is a real one, not a replay of recorded latencies. Every
job k is released at `origin + k * period` and is due at `origin + (k+1) *
period`, both computed from a single monotonic origin. Sleeping for
`period - work` each iteration instead would accumulate the sleep's own
overshoot into a drift of tens of milliseconds over a few hundred jobs, and
the drift would then be reported as jitter.

Overrun is not queued away. If job k finishes after job k+1 was due, job k+1
starts immediately and late, which is what a best-effort SensorDataQoS
subscriber does with a backlog it cannot clear (docs/ROS2.md). Both the
lateness at the start of a job and the lateness at its end are recorded.

Both implementations run under the same Python scheduler so the scheduler's
own cost and noise are charged equally. The C++ pipeline is reached through a
C ABI shim compiled against the same `libgrasp_core.a` that
`cpp/build/bench_pipeline` links, with the compile flags read out of the CMake
build tree so the shim cannot drift from the library. The latency reported for
a job is the pipeline's own `total_ns`, measured inside the pipeline by the
same instrumentation the in-process benchmark uses, so the ctypes call is not
inside it; the ctypes round trip is measured separately and reported in the
metadata so a reader can see what the scheduler's view of a job costs on top.

Usage:
  rate_sweep.py --out-dir results
  rate_sweep.py --dataset data/table_320x240 --rates 10 30 100 --jobs 100
"""
from __future__ import annotations

